#!/usr/bin/env bash
# Freeze the AVX-512 f64 24x8 real micro-kernel's compiler-generated x86-64
# assembly into a checked-in `.S` file, and prove/refute that the kernel is
# instruction-identical with and without `-C target-cpu=native`.
#
# Steps:
#   1. build `tcontract-kernel` twice (native and baseline `x86-64` target) with
#      `--emit=asm` into separate target dirs;
#   2. extract the f64 kernel bodies (`tramp_real::<3,8>` and `real::<3,8>`);
#   3. diff the two instruction streams;
#   4. write the native body to `asm/avx512_f64_real_24x8.S` under a stable
#      symbol name, with a provenance header and the tcontract license.
#
# Usage: ./freeze.sh
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
out="$here/asm/avx512_f64_real_24x8.S"
diff_out="$here/asm/native-vs-baseline.diff"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
NATIVE_TARGET="$tmp/native"
BASE_TARGET="$tmp/baseline"

echo "== building tcontract-kernel (native and baseline) with --emit=asm =="
(
  cd "$root"
  RUSTFLAGS='-C target-cpu=native' CARGO_TARGET_DIR="$NATIVE_TARGET" CARGO_BUILD_JOBS="${CARGO_BUILD_JOBS:-16}" \
    cargo rustc -p tcontract-kernel --release --lib -- --emit=asm >/dev/null
  RUSTFLAGS='-C target-cpu=x86-64' CARGO_TARGET_DIR="$BASE_TARGET" CARGO_BUILD_JOBS="${CARGO_BUILD_JOBS:-16}" \
    cargo rustc -p tcontract-kernel --release --lib -- --emit=asm >/dev/null
)

native_s="$(find "$NATIVE_TARGET" -name 'tcontract_kernel-*.s' -print -quit)"
base_s="$(find "$BASE_TARGET" -name 'tcontract_kernel-*.s' -print -quit)"
[[ -n "$native_s" && -n "$base_s" ]] || { echo "could not find emitted .s files" >&2; exit 1; }

export RUSTC_VER="$(rustc --version)"
export LLVM_VER="$(rustc -vV | sed -n 's/^LLVM version: //p')"
export CPU_MODEL="$(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2 | xargs)"
export COMMIT="$(cd "$root" && git rev-parse HEAD)"
export DATE="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
export OUT="$out"
export DIFF_OUT="$diff_out"

python3 - "$native_s" "$base_s" <<'PY'
import os, re, sys

native_s, base_s = sys.argv[1], sys.argv[2]

# The f64 kernel is generated by `simd_kernels!(avx512_f64, f64, __m512d, 8, ...)`
# and mangled (legacy scheme) as `...avx512_f6410tramp_realKj3_Kj8_EBa_` for the
# function-pointer trampoline and `...avx512_f644realKj3_Kj8_EBa_` for the
# `#[target_feature]` body. Under `-C target-cpu=native` LLVM inlines `real`
# into `tramp_real` (global avx512f), so the native tramp IS the kernel body;
# under `-C target-cpu=x86-64` it cannot, so `tramp_real` is a `jmp` and `real`
# is the body. We therefore compare the native tramp against the baseline real.
NATIVE_NEEDLE = "f6410tramp_realKj3_Kj8_EBa_"
BASE_REAL_NEEDLE = "f644realKj3_Kj8_EBa_"
BASE_TRAMP_NEEDLE = "f6410tramp_realKj3_Kj8_EBa_"

def extract(path, needle):
    lines = open(path, encoding="utf-8").read().splitlines()
    # label line: `<mangled>:` — a bare symbol definition containing the needle
    for i, l in enumerate(lines):
        if l.endswith(":") and needle in l and not l.startswith(".") and "@" not in l:
            # walk back to include the `.section` line
            s = i
            while s > 0 and not lines[s - 1].startswith("\t.section"):
                s -= 1
            for j in range(i, len(lines)):
                if lines[j].startswith("\t.size") and needle in lines[j]:
                    return lines[s - 1 : j + 1]
    raise SystemExit(f"needle {needle} not found in {path}")

def instructions(body):
    out = []
    for l in body:
        if l.startswith("\t") and len(l) > 1 and l[1].isalpha():
            out.append(l.strip())
    return out

native_body = extract(native_s, NATIVE_NEEDLE)
base_real = extract(base_s, BASE_REAL_NEEDLE)
base_tramp = extract(base_s, BASE_TRAMP_NEEDLE)

nat_i, base_i = instructions(native_body), instructions(base_real)
print(f"native tramp_real::<3,8> instructions: {len(nat_i)}")
print(f"baseline real::<3,8>  instructions: {len(base_i)}")
print(f"baseline tramp_real::<3,8> is a thin tail-call: "
      f"{'jmp' in instructions(base_tramp)[0] if instructions(base_tramp) else '?'}")

# Canonicalise local labels (`.LBB66_1` vs `.LBB125_1`) so the diff shows only
# real instruction-level differences, then diff.
def canon(lines):
    return [re.sub(r"\.L(BB|func_begin|func_end|tmp)\w*", ".Lx", l) for l in lines]

a, b = canon(nat_i), canon(base_i)
print("\n== normalized instruction diff (native tramp vs baseline real) ==")
import difflib
d = list(difflib.unified_diff(a, b, "native.tramp_real", "baseline.real", lineterm="", n=0))
if not d:
    print("IDENTICAL instruction streams")
else:
    print(f"{len(d)} differing lines (of {len(a)} total)")
    print("\n".join(d))

with open(os.environ["DIFF_OUT"], "w", encoding="utf-8") as f:
    f.write("\n".join(d) + "\n")
print(f"\nwrote normalized diff to {os.environ['DIFF_OUT']}")

# ---- generate the frozen .S from the native tramp body ---------------------
sym = "frozen_real_24x8"
for _l in native_body:
    if "tramp_realKj3_Kj8_EBa_" in _l and "@function" in _l:
        mangled = _l.split(",")[0].split()[-1]
        break
else:
    raise SystemExit("could not find the mangled symbol")

def rewrite(body):
    out_lines = []
    saw_type = False
    for l in body:
        if l.startswith("\t.loc") or l.startswith(".Ltmp") or l.strip() in (".cfi_startproc", ".cfi_endproc"):
            continue
        if l.startswith("\t.section"):
            out_lines.append("\t.text")
        elif ".prefalign" in l:
            out_lines.append("\t.p2align\t4")
        elif l.startswith("\t.type") and mangled in l:
            out_lines.append(f"\t.type\t{sym},@function")
            saw_type = True
        elif l == mangled + ":":
            out_lines.append(f"{sym}:")
        elif l.startswith("\t.size") and mangled in l:
            out_lines.append(f"\t.size\t{sym}, .-{sym}")
        else:
            out_lines.append(l)
    return out_lines, saw_type

body, saw_type = rewrite(native_body)

header = f"""\
# Frozen compiler-generated assembly of
#   tcontract_kernel::kernels::x86::avx512_f64::real::<3,8>
# (the `-C target-cpu=native` build inlines `real` into its function-pointer
# trampoline `tramp_real::<3,8>`, so the frozen symbol below is the whole
# micro-kernel body, not the trampoline).
#
# Generated by freeze.sh — do not hand-edit.
#   source:     crates/tcontract-kernel/src/kernels/macros.rs  (`simd_kernels!`)
#   instantiated: crates/tcontract-kernel/src/kernels/x86/avx512.rs (`avx512_f64`)
#   rustc:      {os.environ['RUSTC_VER']}
#   LLVM:       {os.environ['LLVM_VER']}
#   flags:      -C target-cpu=native (release, opt-level=3, lto=thin, cgu=1)
#   host CPU:   {os.environ['CPU_MODEL']} (avx512f)
#   tcontract-rs:  {os.environ['COMMIT']}
#   date:       {os.environ['DATE']}
#
# Signature (SysV x86-64): rdi=kc, rsi=a, rdx=b, rcx=ab
#   void frozen_real_24x8(usize kc, const f64* a, const f64* b, f64* ab)
#   tile contract: ab[j*24 + i] = sum_p a[p*24 + i] * b[p*8 + j]
#
# Copyright (c) the tensor4all contributors.
# SPDX-License-Identifier: MIT OR Apache-2.0
# (the generated kernel text derives from Lukas Devos's tensorprimitives-rs,
# MIT OR Apache-2.0; see crates/tcontract-kernel and docs/provenance.md)
"""

globl = f"\t.globl\t{sym}\n"
if saw_type:
    # insert .globl right before the .type line
    final = []
    for l in body:
        if l.startswith("\t.type\t") and sym in l:
            final.append(globl.rstrip("\n"))
        final.append(l)
    body = final
else:
    body = [globl.rstrip("\n")] + body

with open(os.environ["OUT"], "w", encoding="utf-8") as f:
    f.write(header)
    f.write("\n".join(body))
    f.write("\n")
print(f"wrote frozen assembly to {os.environ['OUT']} ({len(body)} body lines)")
PY

echo "== freeze complete =="
